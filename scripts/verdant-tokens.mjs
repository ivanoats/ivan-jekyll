// Generates the Sass side of the Verdant design system for this Jekyll site.
//
// Verdant ships as a PandaCSS preset, but this site is styled with Sass on
// top of minimal-mistakes, so instead of running Panda we read the preset's
// token and theme modules and write them out as:
//
//   _sass/verdant/_tokens.scss       Sass variables (light values, for the
//                                    theme's colour maths) and mixins that
//                                    emit Verdant's --colors-* custom
//                                    properties for light, dark and the
//                                    prefers-contrast: more sets.
//   assets/js/verdant-theme-toggle.js The package's System/Light/Dark runtime.
//
// Both outputs are committed so `bundle exec jekyll serve` works without
// Node; the Netlify build reruns this so they always match the installed
// package version. Run with `npm run verdant`.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  fontFamilyTokens, spacingTokens, radiiTokens, fontSizeTokens, lineHeightTokens,
} from '@sustainablewebsites/verdant-design/tokens'
import { themeTokens, highContrastTokens, themeVarName } from '@sustainablewebsites/verdant-design/theme'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const pkgDir = dirname(require.resolve('@sustainablewebsites/verdant-design/theme'))
const { version } = JSON.parse(readFileSync(join(pkgDir, '..', 'package.json'), 'utf8'))

// surface.100 -> surface-100, accent.ink -> accent-ink, focusRing -> focus-ring
const sassName = (name) => themeVarName(name).replace(/^--colors-/, '')
const kebab = (key) => String(key).replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase()

const scalar = (prefix, tokens) =>
  Object.entries(tokens).map(([key, value]) => `$verdant-${prefix}-${kebab(key)}: ${value};`)

const varsMixin = (name, tokens, mode) => [
  `@mixin ${name} {`,
  ...Object.entries(tokens).map(([key, value]) => `  ${themeVarName(key)}: ${value[mode]};`),
  '}',
]

const scss = [
  `// GENERATED by scripts/verdant-tokens.mjs from @sustainablewebsites/verdant-design@${version}.`,
  '// Do not edit by hand: change the package version and run `npm run verdant`.',
  '',
  `$verdant-version: "${version}";`,
  '',
  '// Typography',
  ...scalar('font', fontFamilyTokens),
  ...scalar('font-size', fontSizeTokens),
  ...scalar('line-height', lineHeightTokens),
  '',
  '// Spacing and radii',
  ...scalar('space', spacingTokens),
  ...scalar('radius', radiiTokens),
  '',
  '// Light values as plain Sass colours, for minimal-mistakes variables that',
  '// feed colour functions at compile time. Runtime styling should use the',
  '// custom properties below so it follows the active theme.',
  ...Object.entries(themeTokens).map(([key, value]) => `$verdant-${sassName(key)}: ${value.light};`),
  '',
  ...varsMixin('verdant-colors-light', themeTokens, 'light'),
  '',
  ...varsMixin('verdant-colors-dark', themeTokens, 'dark'),
  '',
  '// prefers-contrast: more (7:1 text, 4.5:1 boundaries)',
  ...varsMixin('verdant-colors-high-contrast-light', highContrastTokens, 'light'),
  '',
  ...varsMixin('verdant-colors-high-contrast-dark', highContrastTokens, 'dark'),
  '',
].join('\n')

mkdirSync(join(root, '_sass/verdant'), { recursive: true })
writeFileSync(join(root, '_sass/verdant/_tokens.scss'), scss)
copyFileSync(join(pkgDir, 'theme-toggle.js'), join(root, 'assets/js/verdant-theme-toggle.js'))

console.log(`verdant: wrote tokens and theme runtime from verdant-design@${version}`)
