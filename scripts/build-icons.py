"""Generate _sass/_icons.scss: the 15 Font Awesome icons this site uses, as CSS masks."""
from pathlib import Path
from urllib.parse import quote
import re

# Run `npm install --no-save @fortawesome/fontawesome-free` first.
pkg = Path(__file__).resolve().parent.parent / 'node_modules/@fortawesome/fontawesome-free/svgs'
out = Path(__file__).resolve().parent.parent / '_sass' / '_icons.scss'

# class name used in the theme's HTML -> source SVG
icons = {
    'fa-square-rss': 'solid/square-rss',
    'fa-square-envelope': 'solid/square-envelope',
    'fa-location-dot': 'solid/location-dot',
    'fa-calendar-alt': 'solid/calendar-days',
    'fa-tags': 'solid/tags',
    'fa-link': 'solid/link',
    'fa-check': 'solid/check',
    'fa-clock': 'regular/clock',
    'fa-copy': 'regular/copy',
    'fa-linkedin': 'brands/linkedin',
    'fa-stack-overflow': 'brands/stack-overflow',
    'fa-instagram': 'brands/instagram',
    'fa-github': 'brands/github',
    'fa-facebook': 'brands/facebook',
    'fa-bluesky': 'brands/bluesky',
}

lines = [
    '/*! Icons: Font Awesome Free 7.3.1 by @fontawesome, https://fontawesome.com',
    '    License: CC BY 4.0 (https://fontawesome.com/license/free).',
    '    Generated by scripts/build-icons.py: only the icons this site uses, as CSS masks,',
    '    so the site no longer loads the full Font Awesome stylesheet and webfonts from a CDN. */',
    '',
    '.fa, .fas, .far, .fab {',
    '  display: inline-block;',
    '  width: 1em;',
    '  height: 1em;',
    '  vertical-align: -0.125em;',
    '  background-color: currentColor;',
    '  -webkit-mask: var(--icon) center / contain no-repeat;',
    '  mask: var(--icon) center / contain no-repeat;',
    '}',
    '.fa-fw { width: 1.25em; }',
    '',
]
for cls, src in icons.items():
    svg = (pkg / f'{src}.svg').read_text()
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = svg.replace(' fill="currentColor"', '').strip()
    uri = 'data:image/svg+xml,' + quote(svg, safe=' =:/,;"')
    uri = uri.replace('"', "'")
    lines.append(f'.{cls} {{ --icon: url("{uri}"); }}')

# Masks paint with background-color, which forced-colors mode (Windows High Contrast)
# resets to the page background. Keep the mask and paint it with a system color.
lines += [
    '',
    '@media (forced-colors: active) {',
    '  .fa, .fas, .far, .fab { forced-color-adjust: none; background-color: CanvasText; }',
    '  a .fa, a .fas, a .far, a .fab { background-color: LinkText; }',
    '}',
]
out.write_text('\n'.join(lines) + '\n')
print('wrote', out, out.stat().st_size, 'bytes')
